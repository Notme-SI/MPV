return function(path)
    local f=dofile(path('extensions/title_format.lua'))
    local a=f.parse('Reacher.S01E04.In.a.Tree.2160p.WEB-DL.HDR.HEVC.mkv')
    assert(a.title=='Reacher' and a.season==1 and a.episode==4 and a.episode_title=='In a Tree')
    assert(f.label(a,'ru','Джек Ричер','На дереве')=='Джек Ричер · Сезон 1, серия 4: На дереве')
    assert(f.label(a,'en')=='Reacher · Season 1, episode 4: In a Tree')
    local b=f.parse('S01E04. MobLand (2025). Rat Trap.2160p.mkv')
    assert(b.title=='MobLand' and b.year=='2025' and b.episode_title=='Rat Trap')
    local c=f.parse('They.Live.1988.1080p.BluRay.x264.mkv')
    assert(c.title=='They Live' and c.year=='1988' and c.kind=='movie')
    assert(f.parse('1917.2019.2160p.mkv').title=='1917')
    assert(f.parse('2001.A.Space.Odyssey.1968.1080p.mkv').title=='2001 A Space Odyssey')
    assert(f.parse('[SubsPlease] Gachiakuta - 03 [1080p].mkv').episode==3)
    local anime=f.parse('Kusuriya.no.Hitorigoto.S3 - 02 [1080p].mkv')
    assert(anime.title=='Kusuriya no Hitorigoto' and anime.season==3 and anime.episode==2)
    assert(f.parse('Kusuriya no Hitorigoto S3').season==3)
    local alias={id=220542,name='Монолог фармацевта',original_name='薬屋のひとりごと',aliases={{title='Kusuriya no Hitorigoto'}}}
    assert(f.match_result({alias},anime).id==220542,'Romanized name must be confirmed by a catalog alias')
    assert(not f.match_result({{id=9,name='Unrelated Anime',aliases={{title='Other show'}}}},anime))
    assert(not f.match_result({alias,alias},anime),'Ambiguous aliases must not pick a random show')
    local candidates=f.animation_candidates({{id=333686,genre_ids={18,9648}},{id=220542,genre_ids={16,18,9648}}})
    assert(#candidates==1 and candidates[1].id==220542,'Known anime must not select its live-action adaptation')
    assert(#f.animation_candidates({{id=1,genre_ids={18}}})==0)
    assert(f.parse('Ричер.S01E01.1080p.mkv').title=='Ричер')
    assert(f.parse('http://localhost:8090/stream?link=private').title=='')
    assert(f.language('rus')=='ru' and f.language('en-US')=='en' and f.language('ukr')=='uk')
    assert(f.match_result({{id=1,name='Ричер',original_name='Reacher',first_air_date='2022-01-01'}},a).id==1)
    assert(not f.match_result({{id=2,name='Preacher'}},a))
    assert(not f.match_result({{id=1,name='Reacher'},{id=2,name='Reacher'}},a))
    local movie=f.parse('Protector.2025.2160p.WEB-DL.mkv')
    local near={id=1383731,title='Мститель',original_title='Protector',release_date='2026-02-20'}
    assert(not f.match_result({near},movie),'Initial search keeps exact year')
    assert(f.match_result({near},movie,true).id==1383731,'One-year release offset')
    assert(not f.match_result({near,{id=2,title='Protector',release_date='2024-01-01'}},movie,true),'Ambiguous nearby years')
    assert(not f.match_result({{id=3,title='Protector',release_date='2023-01-01'}},movie,true),'Different release')
    assert(f.match_result({near,{id=4,title='Protector',release_date='2025-01-01'}},movie,true).id==4,'Exact year wins')
end
